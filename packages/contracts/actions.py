"""Action and Policy Decision Contracts for ARGUS.

Defines the typed boundary contracts between the Agent Planner,
the Deterministic Policy Engine, and the Tool Execution Engine.
"""

import hashlib
import json
from datetime import UTC, datetime
from enum import Enum
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field


class MinimumProofType(str, Enum):
    """Threshold of verified evidence required to declare exploitation success."""

    CODE_EXECUTION = "code_execution"  # Demonstrated command execution (whoami, id, uname)
    DATA_EXPOSURE = "data_exposure"  # Arbitrary file read (/etc/passwd, db dumps, tokens)
    AUTH_BYPASS = "auth_bypass"  # Verified privileged session token or admin login
    SIMULATED_CANARY = "simulated_canary"  # Simulated probe canary confirmation (for air-gapped demo labs)


class ExploitChainObjective(BaseModel):
    """Specification for multi-step attack path and exploitation objectives."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    type: Literal["exploit_chain"] = "exploit_chain"
    target_asset: str | None = Field(
        default=None, description="Primary asset to demonstrate impact on"
    )
    minimum_proof: MinimumProofType = Field(
        default=MinimumProofType.DATA_EXPOSURE,
        description="Minimum cryptographic proof required to confirm impact",
    )
    allow_pivoting: bool = Field(
        default=False,
        description="Whether multi-host lateral movement is authorized (enforces chain.enabled)",
    )
    max_chain_depth: int = Field(default=3, ge=1, le=5, description="Maximum chained attack steps")
    flag_pattern: str | None = Field(
        default=None, description="Optional CTF flag regex pattern, e.g. flag{...}"
    )


class FootholdType(str, Enum):
    """Mechanisms of demonstrated access that can unlock a pivot edge."""

    VERIFIED_CREDENTIAL = "VERIFIED_CREDENTIAL"  # Validated login (SSH/DB/HTTP auth)
    COMMAND_EXECUTION = "COMMAND_EXECUTION"  # Confirmed RCE / non-destructive command token
    NETWORK_TUNNEL = "NETWORK_TUNNEL"  # Active SOCKS/HTTP forwarder established


class FootholdEvidence(BaseModel):
    """Cryptographic proof of active compromise required to traverse a pivot edge."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    foothold_id: str = Field(..., description="Unique foothold identifier (e.g. fh-20261106-001)")
    assessment_id: str = Field(..., description="Owning assessment; footholds cannot cross assessments")
    host: str = Field(..., description="IP or hostname where foothold is established")
    foothold_type: FootholdType = Field(..., description="Class of operational access achieved")
    finding_id: str = Field(..., description="Parent confirmed finding proving root vulnerability")
    evidence_id: str = Field(..., description="SHA-256 evidence artifact proving validity of access")
    established_at: datetime = Field(default_factory=lambda: datetime.now(UTC))
    expires_at: datetime = Field(..., description="TTL after which foothold must be re-validated")
    simulated: bool = Field(default=False, description="Taint flag: simulated footholds cannot unlock live pivots")
    details: dict[str, Any] = Field(default_factory=dict, description="Redacted access parameters")

    def is_expired(self, current_time: datetime | None = None) -> bool:
        now = current_time or datetime.now(UTC)
        exp = (
            self.expires_at
            if self.expires_at.tzinfo is not None
            else self.expires_at.replace(tzinfo=UTC)
        )
        return now > exp


class ActionProposal(BaseModel):
    """Structured action proposal generated by the agent or test harness."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    action_id: str = Field(..., description="Unique action tracking ID, e.g. act-001")
    target_host: str = Field(..., description="Target hostname or IP address")
    target_port: int | None = Field(default=None, description="Target TCP/UDP port")
    tool_name: str = Field(
        ..., description="Name of registered tool adapter (e.g. nmap, zap, nuclei)"
    )
    action_category: str = Field(
        ..., description="Category of action (network_recon, web_crawl, active_template_check)"
    )
    arguments: dict[str, Any] = Field(
        default_factory=dict, description="Typed parameters for the tool adapter"
    )
    rationale: str = Field(..., description="LLM explanation for why this action is required")
    expected_evidence: str = Field(
        ..., description="Hypothesis of what evidence should be returned"
    )
    timeout_seconds: int = Field(default=120, ge=5, le=600, description="Execution timeout limit")
    parent_action_id: str | None = Field(
        default=None,
        description="Pointer to preceding action ID for multi-step chained verification (L-04)",
    )
    step_index: int | None = Field(
        default=None, description="Sequence step index within a multi-step objective"
    )

    def fingerprint(self) -> str:
        """Deterministic fingerprint to detect redundant or duplicate proposals.

        Chain metadata is included so a legitimate later step is not rejected as a
        duplicate merely because it reuses the same tool, target, and arguments.
        """
        raw = (
            f"{self.tool_name}:{self.target_host}:{self.target_port}:"
            f"{self.action_category}:{self.parent_action_id}:{self.step_index}:"
            f"{json.dumps(self.arguments, sort_keys=True, default=str)}"
        )
        return hashlib.sha256(raw.encode()).hexdigest()[:16]


class PolicyDecision(BaseModel):
    """Deterministic verdict emitted by the Scope Policy Engine."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    approved: bool = Field(..., description="Whether the action is authorized to execute")
    reason: str = Field(
        ..., description="Deterministic explanation of why the action was approved or denied"
    )
    resolved_ip: str | None = Field(
        default=None, description="The verified IP address resolved and checked against the scope"
    )


class DecisionType(str, Enum):
    """High-level assessment lifecycle decisions made by the agent."""

    EXECUTE_ACTION = "EXECUTE_ACTION"
    RESEARCH_INTEL = "RESEARCH_INTEL"
    OBJECTIVE_ACHIEVED = "OBJECTIVE_ACHIEVED"
    BLOCKED = "BLOCKED"
    NEEDS_CLARIFICATION = "NEEDS_CLARIFICATION"


class AssessmentDecision(BaseModel):
    """Decouples high-level assessment intent from raw tool execution."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    decision_type: DecisionType = Field(..., description="The agent's strategic decision")
    rationale: str = Field(..., description="Strategic reasoning for this decision")
    proposed_action: ActionProposal | None = Field(
        default=None, description="Proposed tool execution when decision_type is EXECUTE_ACTION"
    )
    intel_query: str | None = Field(
        default=None, description="Contextual search query when decision_type is RESEARCH_INTEL"
    )
    completion_summary: str | None = Field(
        default=None, description="Summary of verified results when objective is achieved"
    )
